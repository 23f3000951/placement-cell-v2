# Task 3: Export CSV — Async job triggered by student
# ============================================================
@celery.task()
def export_csv(student_id):
    app = get_app()
    with app.app_context():
        from extensions import mail
        from models import Application, PlacementDrive, User

        student = User.query.get(student_id)
        if not student:
            return "Student not found."

        apps = Application.query.filter_by(student_id=student_id).all()

        # Write CSV
        export_dir = os.path.join(os.path.dirname(__file__), 'exports')
        os.makedirs(export_dir, exist_ok=True)
        filename = f"applications_{student_id}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.csv"
        filepath = os.path.join(export_dir, filename)

        with open(filepath, 'w', newline='', encoding='utf-8') as f:
            writer = csv.writer(f)
            writer.writerow(['Student ID', 'Company Name', 'Drive Title', 'Application Status', 'Applied Date', 'Interview Date'])
            for a in apps:
                drive = PlacementDrive.query.get(a.drive_id)
                company = User.query.get(drive.company_id)
                writer.writerow([
                    student_id,
                    company.name if company else 'N/A',
                    drive.title if drive else 'N/A',
                    a.status,
                    a.applied_at.strftime('%Y-%m-%d') if a.applied_at else '',
                    a.interview_date.strftime('%Y-%m-%d %H:%M') if a.interview_date else ''
                ])

        # Send notification email
        body = f"Hi {student.name},\n\nYour application history CSV has been exported successfully.\nFile: {filename}\n\nRegards,\nPlacement Cell"
        msg = Message(
            subject="Your Application Export is Ready",
            recipients=[student.email],
            body=body
        )
        _save_email_to_file(msg, student.email, 'csv_export')
        try:
            mail.send(msg)
        except Exception as e:
            print(f"[CSV Export] Mail send error (suppressed): {e}")

        print(f"[CSV Export] Exported {len(apps)} applications for student {student.name} to {filename}")
        return filepath


# ============================================================
# Helper: Save email as file (for demo/presentation)
# ============================================================
def _save_email_to_file(msg, recipient, task_type):
    """Save email content to a text file so it can be shown during presentation."""
    email_dir = os.path.join(os.path.dirname(__file__), 'sent_emails')
    os.makedirs(email_dir, exist_ok=True)
    timestamp = datetime.now().strftime('%Y%m%d_%H%M%S')
    filename = f"{task_type}_{recipient}_{timestamp}.txt"
    filepath = os.path.join(email_dir, filename)
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(f"To: {', '.join(msg.recipients)}\n")
        f.write(f"Subject: {msg.subject}\n")
        f.write(f"From: {msg.sender}\n")
        f.write(f"Date: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")
        f.write(f"{'='*50}\n\n")
        if msg.html:
            f.write(msg.html)
        else:
            f.write(msg.body)
    print(f"[Email Saved] {filepath}")
