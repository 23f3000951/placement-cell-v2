import csv
import os
from datetime import datetime, timezone, timedelta
from celery_config import celery
from flask_mail import Message


def get_app():
    """Create Flask app context for Celery tasks."""
    from app import create_app
    return create_app()


# ============================================================
# Task 1: Daily Reminders — Email students about upcoming deadlines
# ============================================================
@celery.task()
def send_daily_reminders():
    app = get_app()
    with app.app_context():
        from extensions import mail
        from models import PlacementDrive, User, Role, StudentProfile

        # Find drives with deadlines in the next 3 days
        now = datetime.now(timezone.utc)
        upcoming = now + timedelta(days=3)
        drives = PlacementDrive.query.filter(
            PlacementDrive.status == 'Approved',
            PlacementDrive.deadline >= now,
            PlacementDrive.deadline <= upcoming
        ).all()

        if not drives:
            print("[Daily Reminder] No upcoming deadlines found.")
            return "No upcoming deadlines."

        # Get all student emails
        student_role = Role.query.filter_by(name='student').first()
        if not student_role:
            return "No students found."
        students = student_role.users

        # Build drive list text
        drive_lines = ""
        for d in drives:
            company = User.query.get(d.company_id)
            drive_lines += f"  - {d.title} by {company.name} | Deadline: {d.deadline.strftime('%d %b %Y')}\n"

        # Send email to each student
        count = 0
        for student in students:
            if not student.active:
                continue
            body = f"Hi {student.name},\n\nThe following placement drives have upcoming deadlines:\n\n{drive_lines}\nPlease apply before the deadline!\n\nRegards,\nPlacement Cell"
            msg = Message(
                subject="Reminder: Upcoming Placement Drive Deadlines",
                recipients=[student.email],
                body=body
            )
            # Save email to file (for demo)
            _save_email_to_file(msg, student.email, 'daily_reminder')
            try:
                mail.send(msg)
            except Exception as e:
                print(f"[Daily Reminder] Mail send error (suppressed): {e}")
            count += 1

        print(f"[Daily Reminder] Sent reminders to {count} students for {len(drives)} drives.")
        return f"Sent {count} reminders."


