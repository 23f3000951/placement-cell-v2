# Task 2: Monthly Report — HTML report emailed to Admin
# ============================================================
@celery.task()
def send_monthly_report():
    app = get_app()
    with app.app_context():
        from extensions import mail
        from models import PlacementDrive, Application, Role

        # Gather stats
        total_drives = PlacementDrive.query.count()
        approved_drives = PlacementDrive.query.filter_by(status='Approved').count()
        total_applications = Application.query.count()
        total_selected = Application.query.filter_by(status='Selected').count()
        total_shortlisted = Application.query.filter_by(status='Shortlisted').count()
        total_rejected = Application.query.filter_by(status='Rejected').count()

        # Build HTML report
        month_name = datetime.now().strftime('%B %Y')
        html = f"""
        <html>
        <body style="font-family: Arial, sans-serif; padding: 20px;">
            <h2>Monthly Placement Activity Report — {month_name}</h2>
            <table border="1" cellpadding="8" cellspacing="0" style="border-collapse: collapse;">
                <tr><td><strong>Total Drives</strong></td><td>{total_drives}</td></tr>
                <tr><td><strong>Approved Drives</strong></td><td>{approved_drives}</td></tr>
                <tr><td><strong>Total Applications</strong></td><td>{total_applications}</td></tr>
                <tr><td><strong>Students Selected</strong></td><td>{total_selected}</td></tr>
                <tr><td><strong>Students Shortlisted</strong></td><td>{total_shortlisted}</td></tr>
                <tr><td><strong>Students Rejected</strong></td><td>{total_rejected}</td></tr>
            </table>
            <p style="margin-top: 20px; color: #666;">This report was auto-generated by the Placement Cell system.</p>
        </body>
        </html>
        """

        msg = Message(
            subject=f"Monthly Placement Report — {month_name}",
            recipients=['admin@institute.com'],
            html=html
        )
        _save_email_to_file(msg, 'admin@institute.com', 'monthly_report')
        try:
            mail.send(msg)
        except Exception as e:
            print(f"[Monthly Report] Mail send error (suppressed): {e}")

        print(f"[Monthly Report] Report generated and sent for {month_name}.")
        return f"Report sent for {month_name}."


